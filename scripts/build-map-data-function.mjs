// Bundles supabase/functions/map-data/build.ts (and the app's parsing code it imports) into
// one file for Supabase Dashboard → Edge Functions → Via Editor. Run: node scripts/build-map-data-function.mjs
import { build } from 'esbuild';
import path from 'node:path';

const i18nStub = {
  name: 'i18n-stub',
  setup(b) {
    b.onResolve({ filter: /(^|\/)i18n$/ }, () => ({ path: path.resolve('supabase/functions/map-data/i18n-stub.ts') }));
  },
};
await build({
  plugins: [i18nStub],
  entryPoints: ['supabase/functions/map-data/build.ts'],
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  outfile: 'supabase/functions/map-data/dashboard-paste.ts',
  external: ['expo-localization'],
  define: { __DEV__: 'false', 'process.env.EXPO_PUBLIC_SUPABASE_URL': '""' },
  banner: { js: '// GENERATED by scripts/build-map-data-function.mjs: do not edit. Paste into Supabase as function "map-data".\n// @ts-nocheck' },
  legalComments: 'none',
  minify: true,
});
console.log('wrote supabase/functions/map-data/dashboard-paste.ts');
