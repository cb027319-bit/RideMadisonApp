// Builds supabase/functions/welcome-email/dashboard-paste.ts: index.ts + template.ts in ONE
// file, for pasting into Supabase Dashboard → Edge Functions → Deploy via editor.
// Run: node scripts/build-welcome-email.mjs
import { readFileSync, writeFileSync } from 'node:fs';
const dir = 'supabase/functions/welcome-email';
const template = readFileSync(`${dir}/template.ts`, 'utf8').replace(/^export /gm, '');
const index = readFileSync(`${dir}/index.ts`, 'utf8').replace(/^import \{ welcomeEmail, type WelcomeLang \} from '\.\/template\.ts';\n/m, '');
const out = `// GENERATED by scripts/build-welcome-email.mjs: do not edit; edit index.ts / template.ts.\n// Paste this whole file into Supabase → Edge Functions → Deploy a new function → Via Editor,\n// name the function "welcome-email".\n\n${template}\n\n${index}`;
writeFileSync(`${dir}/dashboard-paste.ts`, out);
console.log('wrote', `${dir}/dashboard-paste.ts`);
